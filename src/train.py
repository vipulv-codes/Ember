"""Training loop for Ember.

Design goals (plan sections 1 & 2.4):
- bf16 autocast on CUDA, AdamW with no decay on norms/embeddings,
  linear warmup -> cosine decay, gradient accumulation.
- Resumable as a first-class feature: atomic checkpoints every N minutes
  carrying model/optimizer/step/RNG; batch sampling is step-seeded, so a
  resumed run sees exactly the data it would have seen.
- Zero-account logging: CSV per run under experiments/runs/, plots
  regenerated by scripts/plot_loss.py.

Usage:
    python src/train.py --config configs/ember_30m_hero.py [--resume] [key=value ...]
"""

import argparse
import csv
import math
import os
import time
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np
import torch

from model import Ember, preset_config

ROOT = Path(__file__).resolve().parents[1]


@dataclass
class TrainConfig:
    run_name: str = "dev"
    # model
    preset: str = "ember-5m"
    vocab_size: int = 8192
    ctx_len: int = 512
    attn_impl: str = "sdpa"
    # ablation axes (model.py defaults = the Ember stack)
    pos_encoding: str = "rope"
    norm_type: str = "rmsnorm"
    norm_placement: str = "pre"
    ffn_type: str = "swiglu"
    ffn_hidden: int = 0  # 0 = use the preset's value (gelu runs override to 1.5x)
    # data (paths relative to repo root)
    train_bin: str = "data/train.bin"
    val_bin: str = "data/val.bin"
    # optimization
    total_tokens: int = 600_000_000
    micro_bsz: int = 32
    accum_steps: int = 16
    peak_lr: float = 3e-4
    min_lr_ratio: float = 0.1
    warmup_frac: float = 0.02
    weight_decay: float = 0.1
    betas: tuple = (0.9, 0.95)
    grad_clip: float = 1.0
    # cadence
    log_interval: int = 10  # steps
    eval_interval: int = 100  # steps
    eval_batches: int = 32
    ckpt_interval_sec: int = 900
    # misc
    seed: int = 1337
    device: str = "cuda"
    compile: bool = False

    @property
    def tokens_per_step(self) -> int:
        return self.micro_bsz * self.ctx_len * self.accum_steps

    @property
    def total_steps(self) -> int:
        return self.total_tokens // self.tokens_per_step

    @property
    def warmup_steps(self) -> int:
        return max(1, int(self.total_steps * self.warmup_frac))


def load_config(path: str, overrides: list[str]) -> TrainConfig:
    cfg = TrainConfig()
    ns: dict = {}
    exec(Path(path).read_text(), ns)
    for k, v in ns.items():
        if not k.startswith("_") and hasattr(cfg, k):
            setattr(cfg, k, v)
    for ov in overrides:
        k, v = ov.split("=", 1)
        cur = getattr(cfg, k)  # KeyError-like fail on unknown key
        setattr(cfg, k, type(cur)(eval(v)) if not isinstance(cur, str) else v)
    return cfg


def get_batch(data: np.memmap, cfg: TrainConfig, step: int, micro: int, split_salt: int):
    """Step-seeded random crops -> exact-resume determinism for free.

    Known quirk, kept for reproducibility of published runs: with
    accum_steps > 61 the (step*61 + micro*7) mix collides, so micros 61-63
    at step s repeat micros 0-2 of step s+7 (~4.7% duplicate batches at
    accum 64). Statistically negligible, identical across compared runs.
    """
    g = torch.Generator().manual_seed(cfg.seed * 1_000_003 + step * 61 + micro * 7 + split_salt)
    ix = torch.randint(0, len(data) - cfg.ctx_len - 1, (cfg.micro_bsz,), generator=g)
    x = torch.stack([torch.from_numpy(data[i : i + cfg.ctx_len].astype(np.int64)) for i in ix])
    y = torch.stack(
        [torch.from_numpy(data[i + 1 : i + 1 + cfg.ctx_len].astype(np.int64)) for i in ix]
    )
    if cfg.device == "cuda":
        x = x.pin_memory().to(cfg.device, non_blocking=True)
        y = y.pin_memory().to(cfg.device, non_blocking=True)
    return x, y


def lr_at(step: int, cfg: TrainConfig) -> float:
    if step < cfg.warmup_steps:
        return cfg.peak_lr * (step + 1) / cfg.warmup_steps
    progress = (step - cfg.warmup_steps) / max(1, cfg.total_steps - cfg.warmup_steps)
    coeff = 0.5 * (1 + math.cos(math.pi * min(1.0, progress)))
    min_lr = cfg.peak_lr * cfg.min_lr_ratio
    return min_lr + coeff * (cfg.peak_lr - min_lr)


def make_optimizer(model: Ember, cfg: TrainConfig) -> torch.optim.AdamW:
    decay, no_decay = [], []
    for name, p in model.named_parameters():
        if p.ndim < 2 or "emb" in name:  # norms + embeddings (tok & pos): no decay
            no_decay.append(p)
        else:
            decay.append(p)
    return torch.optim.AdamW(
        [
            {"params": decay, "weight_decay": cfg.weight_decay},
            {"params": no_decay, "weight_decay": 0.0},
        ],
        lr=cfg.peak_lr,
        betas=tuple(cfg.betas),
    )


@torch.no_grad()
def evaluate(model: Ember, val_data: np.memmap, cfg: TrainConfig, autocast_ctx) -> float:
    model.eval()
    losses = []
    for i in range(cfg.eval_batches):
        x, y = get_batch(val_data, cfg, step=0, micro=i, split_salt=999_331)  # fixed batches
        with autocast_ctx:
            _, loss = model(x, targets=y)
        losses.append(loss.item())
    model.train()
    return float(np.mean(losses))


def save_ckpt(path: Path, model, opt, cfg, step, tokens_seen, best_val):
    model = getattr(model, "_orig_mod", model)  # unwrap torch.compile
    state = {
        "model": model.state_dict(),
        "optimizer": opt.state_dict(),
        "step": step,
        "tokens_seen": tokens_seen,
        "best_val": best_val,
        "config": asdict(cfg),
        "torch_rng": torch.get_rng_state(),
        "cuda_rng": torch.cuda.get_rng_state_all() if torch.cuda.is_available() else None,
    }
    tmp = path.with_suffix(".tmp")
    torch.save(state, tmp)
    os.replace(tmp, path)  # atomic: a crash mid-save never corrupts the checkpoint


def append_csv(path: Path, row: dict):
    new = not path.exists()
    with open(path, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(row))
        if new:
            w.writeheader()
        w.writerow(row)


def truncate_csv_after_step(path: Path, step: int):
    if not path.exists():
        return
    with open(path) as f:
        rows = list(csv.DictReader(f))
    rows = [r for r in rows if int(r["step"]) < step]
    if rows:
        with open(path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    else:
        path.unlink()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--resume", action="store_true")
    ap.add_argument("overrides", nargs="*", help="key=value config overrides")
    args = ap.parse_args()
    cfg = load_config(args.config, args.overrides)

    if cfg.device == "cuda" and not torch.cuda.is_available():
        print("WARNING: cuda requested but unavailable, using cpu")
        cfg.device = "cpu"
    torch.manual_seed(cfg.seed)

    ckpt_dir = ROOT / "checkpoints" / cfg.run_name
    ckpt_dir.mkdir(parents=True, exist_ok=True)
    run_dir = ROOT / "experiments" / "runs"
    run_dir.mkdir(parents=True, exist_ok=True)
    csv_path = run_dir / f"{cfg.run_name}.csv"

    train_data = np.memmap(ROOT / cfg.train_bin, dtype=np.uint16, mode="r")
    val_data = np.memmap(ROOT / cfg.val_bin, dtype=np.uint16, mode="r")

    model_cfg = preset_config(
        cfg.preset,
        vocab_size=cfg.vocab_size,
        ctx_len=cfg.ctx_len,
        attn_impl=cfg.attn_impl,
        pos_encoding=cfg.pos_encoding,
        norm_type=cfg.norm_type,
        norm_placement=cfg.norm_placement,
        ffn_type=cfg.ffn_type,
        **({"ffn_hidden": cfg.ffn_hidden} if cfg.ffn_hidden else {}),
    )
    model = Ember(model_cfg).to(cfg.device)
    opt = make_optimizer(model, cfg)

    start_step, tokens_seen, best_val = 0, 0, float("inf")
    latest = ckpt_dir / "latest.pt"
    if args.resume:
        assert latest.exists(), f"--resume but no checkpoint at {latest}"
        state = torch.load(latest, map_location=cfg.device, weights_only=False)
        model.load_state_dict(state["model"])
        opt.load_state_dict(state["optimizer"])
        start_step = state["step"]
        tokens_seen = state["tokens_seen"]
        best_val = state["best_val"]
        torch.set_rng_state(state["torch_rng"].cpu())
        if state["cuda_rng"] is not None and torch.cuda.is_available():
            torch.cuda.set_rng_state_all([t.cpu() for t in state["cuda_rng"]])
        truncate_csv_after_step(csv_path, start_step)
        print(f"resumed from step {start_step} ({tokens_seen / 1e6:.1f}M tokens)")
    else:
        csv_path.unlink(missing_ok=True)  # fresh run, fresh log

    if cfg.compile:
        model = torch.compile(model)

    n_params = model_cfg.n_params()
    print(
        f"run={cfg.run_name} preset={cfg.preset} params={n_params / 1e6:.1f}M "
        f"steps={cfg.total_steps} tokens/step={cfg.tokens_per_step:,} "
        f"train_tokens={len(train_data) / 1e6:.0f}M device={cfg.device}"
    )

    autocast_ctx = (
        torch.autocast(device_type="cuda", dtype=torch.bfloat16)
        if cfg.device == "cuda"
        else torch.autocast(device_type="cpu", enabled=False)
    )

    model.train()
    t_last_log = time.time()
    t_last_ckpt = time.time()
    t_start = time.time()
    running_loss, running_count = 0.0, 0

    for step in range(start_step, cfg.total_steps):
        lr = lr_at(step, cfg)
        for group in opt.param_groups:
            group["lr"] = lr

        for micro in range(cfg.accum_steps):
            x, y = get_batch(train_data, cfg, step, micro, split_salt=0)
            with autocast_ctx:
                _, loss = model(x, targets=y)
            (loss / cfg.accum_steps).backward()
        torch.nn.utils.clip_grad_norm_(model.parameters(), cfg.grad_clip)
        opt.step()
        opt.zero_grad(set_to_none=True)

        tokens_seen += cfg.tokens_per_step
        running_loss += loss.item()  # last micro-batch loss, cheap proxy between logs
        running_count += 1

        is_last = step == cfg.total_steps - 1
        if step % cfg.log_interval == 0 or is_last:
            dt = time.time() - t_last_log
            tok_s = cfg.tokens_per_step * running_count / dt if dt > 0 else 0.0
            mem = torch.cuda.max_memory_allocated() / 1e9 if cfg.device == "cuda" else 0.0
            row = {
                "step": step,
                "tokens": tokens_seen,
                "lr": f"{lr:.2e}",
                "train_loss": f"{running_loss / max(1, running_count):.4f}",
                "val_loss": "",
                "tok_per_sec": f"{tok_s:.0f}",
                "cuda_mem_gb": f"{mem:.2f}",
                "elapsed_sec": f"{time.time() - t_start:.0f}",
            }
            print(
                f"step {step:5d}/{cfg.total_steps} loss {row['train_loss']} "
                f"lr {row['lr']} {tok_s / 1e3:.1f}k tok/s mem {row['cuda_mem_gb']}GB",
                flush=True,
            )
            running_loss, running_count = 0.0, 0
            t_last_log = time.time()

            if (step % cfg.eval_interval == 0 and step > 0) or is_last:
                val_loss = evaluate(model, val_data, cfg, autocast_ctx)
                row["val_loss"] = f"{val_loss:.4f}"
                print(f"  val_loss {val_loss:.4f} (best {min(best_val, val_loss):.4f})", flush=True)
                if val_loss < best_val:
                    best_val = val_loss
                    save_ckpt(ckpt_dir / "best.pt", model, opt, cfg, step + 1, tokens_seen, best_val)
            append_csv(csv_path, row)

        if time.time() - t_last_ckpt > cfg.ckpt_interval_sec or is_last:
            save_ckpt(latest, model, opt, cfg, step + 1, tokens_seen, best_val)
            t_last_ckpt = time.time()
            print(f"  checkpoint @ step {step + 1}", flush=True)

    print(
        f"done: {tokens_seen / 1e6:.0f}M tokens in {(time.time() - t_start) / 3600:.2f}h, "
        f"best val {best_val:.4f}"
    )


if __name__ == "__main__":
    main()
